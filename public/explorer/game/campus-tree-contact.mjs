export function groundCampusTrees(model) {
  const batch = model.getObjectByName('campus_tile_-2_-2');
  const position = batch?.geometry?.getAttribute('position');
  if (!position?.isInterleavedBufferAttribute || !position.normalized ||
      position.count !== 153063 || position.offset !== 0 ||
      batch.position.y !== 2.259737968444824 || batch.scale.y !== 77.20109939575195) return false;

  const {array, stride} = position.data;
  if (!(array instanceof Int16Array) || stride !== 4) return false;
  // Bind the vertex ranges to the exact decoded order. A replacement model
  // keeps its authored geometry until its own tree offsets have been baked.
  let fingerprint = 2166136261;
  for (const value of array) fingerprint = Math.imul(fingerprint ^ value, 16777619);
  if ((fingerprint >>> 0) !== 3339293751) return false;

  for (const [start, count, drop] of rootDrops) {
    for (let vertex = start; vertex < start + count; vertex++) array[vertex * stride + 1] -= drop;
  }
  position.data.needsUpdate = true;
  batch.geometry.computeBoundingBox();
  batch.geometry.computeBoundingSphere();
  return true;
}

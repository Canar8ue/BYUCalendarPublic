// A member's account always carries a plain @byu.edu address. It matches the
// directory when the published address is exactly that, or when it shares the
// same local part on a byu.edu subdomain (law.byu.edu, ee.byu.edu, ...) — the
// same BYU netid, and the mailbox verification already proved control of it.
export function autoVerifyArea(email) {
  const normalized = String(email || '').toLowerCase();
  if (AUTO_VERIFIED_STAFF.has(normalized)) return AUTO_VERIFIED_STAFF.get(normalized);
  const local = normalized.split('@')[0];
  if (!local) return null;
  for (const [listed, area] of AUTO_VERIFIED_STAFF) {
    const [listedLocal, listedDomain] = listed.split('@');
    if (listedLocal === local && (listedDomain === 'byu.edu' || listedDomain.endsWith('.byu.edu'))) return area;
  }
  return null;
}
